import { Injectable, Logger } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import * as nodemailer from 'nodemailer';
import { JobRecord } from '../../common/interfaces/job.interface.js';
import type { ProcessingHistoryItem } from '../../common/interfaces/processing.interface.js';
import { EmailTemplateService } from './email-template.service.js';

export interface EmailDispatchResult {
  success: boolean;
  messageId?: string;
  recipient: string;
  error?: string;
}

@Injectable()
export class EmailService {
  private readonly logger = new Logger(EmailService.name);
  private transporter: nodemailer.Transporter;
  private readonly defaultRecipient: string;

  constructor(
    private readonly config: ConfigService,
    private readonly templateService: EmailTemplateService,
  ) {
    this.defaultRecipient =
      this.config.get<string>('NOTIFICATION_EMAIL') ||
      this.config.get<string>('SMTP_USER') ||
      'devsanjaikumarv@gmail.com';
    this.initTransporter();
  }

  private initTransporter(): void {
    const host = this.config.get<string>('SMTP_HOST');
    const port = Number(this.config.get<string>('SMTP_PORT')) || 587;
    const user = this.config.get<string>('SMTP_USER');
    const pass =
      this.config.get<string>('SMTP_PASS') ||
      this.config.get<string>('SMTP_PASSWORD');

    if (host && user && pass) {
      const cleanPass = pass.replace(/\s+/g, '');
      this.transporter = nodemailer.createTransport({
        host,
        port,
        secure: port === 465,
        auth: { user, pass: cleanPass },
        tls: { rejectUnauthorized: false },
      });
      this.logger.log(`SMTP transporter configured for host: ${host}:${port}`);
    } else {
      // In local dev/test without credentials, use stream transport (logs to memory/console safely)
      this.transporter = nodemailer.createTransport({
        streamTransport: true,
        newline: 'windows',
      });
      this.logger.warn(
        'No SMTP credentials found in environment. Using stream transport fallback.',
      );
    }
  }

  public async sendJobNotification(
    job: JobRecord,
    recipientEmail?: string,
  ): Promise<EmailDispatchResult> {
    const recipient = recipientEmail || this.defaultRecipient;
    const subject = this.templateService.formatSubject(job);
    const html = this.templateService.renderHtml(job);
    const text = this.templateService.renderPlainText(job);

    try {
      const from =
        this.config.get<string>('SMTP_FROM') || 'noreply@jobmonitor.local';
      const info = await this.transporter.sendMail({
        from: `"Job Notification Alert" <${from}>`,
        to: recipient,
        subject,
        text,
        html,
      });

      this.logger.log(
        `Email successfully dispatched to ${recipient}: ${subject}`,
      );
      return {
        success: true,
        messageId: info.messageId || `msg-${Date.now()}`,
        recipient,
      };
    } catch (err: unknown) {
      const errorMsg = err instanceof Error ? err.message : String(err);
      this.logger.error(
        `Failed to send email notification to ${recipient}: ${errorMsg}`,
      );
      return {
        success: false,
        recipient,
        error: errorMsg,
      };
    }
  }

  public async sendTestEmail(
    recipientEmail?: string,
    customSubject?: string,
    customMessage?: string,
  ): Promise<EmailDispatchResult> {
    const recipient = recipientEmail || this.defaultRecipient;
    const now = new Date().toISOString();
    const testJob: JobRecord = {
      jobId: `TEST-${Date.now().toString(36).toUpperCase()}`,
      jobTitle: customSubject || 'Senior Full Stack Engineer (Test Alert)',
      companyName: 'Acme Systems Corp',
      location: 'Remote / Hybrid',
      employmentType: 'Full-time',
      experience: '5+ years',
      salary: '$140,000 - $180,000',
      description: 'Test job posting generated by the system test suite.',
      applicationUrl: 'http://localhost:3000',
      postedAt: now,
      skills: ['TypeScript', 'NestJS', 'Next.js', 'BullMQ', 'Chokidar'],
      source: 'System Test',
      platform: 'System Integration Test',
      matchScore: '99%',
      matchExplanation:
        customMessage ||
        'This test email confirms that your SMTP and email notification pipeline is operational.',
      sourceFolderId: 'system-tests',
      sourceFileName: 'test-notification.csv',
      createdAt: now,
      updatedAt: now,
    };

    return this.sendJobNotification(testJob, recipient);
  }

  public async sendFileProcessedSummary(
    item: ProcessingHistoryItem,
    recipientEmail?: string,
  ): Promise<EmailDispatchResult> {
    const recipient = recipientEmail || this.defaultRecipient;
    const total = item.recordsTotal ?? 0;
    const valid = item.recordsValid ?? 0;
    const failed = item.recordsFailed ?? 0;
    const duration = item.durationMs ?? 0;
    const subject = `📁 [Job Monitor] Processed: ${item.fileName} (${item.status.toUpperCase()})`;
    const html = `
      <div style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; max-width: 600px; margin: 0 auto; padding: 24px; border: 1px solid #e5e7eb; border-radius: 12px; background: #ffffff;">
        <div style="margin-bottom: 20px; border-bottom: 1px solid #e5e7eb; padding-bottom: 16px;">
          <h2 style="color: #111827; margin: 0 0 6px 0; font-size: 20px;">CSV Ingestion Completed</h2>
          <p style="color: #6b7280; margin: 0; font-size: 13px;">Monitored directory event processed</p>
        </div>
        <table style="width: 100%; border-collapse: collapse; margin-bottom: 20px; font-size: 14px;">
          <tr style="border-bottom: 1px solid #f3f4f6;"><td style="padding: 10px 0; color: #6b7280;">File Name</td><td style="padding: 10px 0; font-weight: 600; color: #111827; text-align: right;">${item.fileName}</td></tr>
          <tr style="border-bottom: 1px solid #f3f4f6;"><td style="padding: 10px 0; color: #6b7280;">Folder</td><td style="padding: 10px 0; font-weight: 600; color: #111827; text-align: right;">${item.folderName}</td></tr>
          <tr style="border-bottom: 1px solid #f3f4f6;"><td style="padding: 10px 0; color: #6b7280;">Status</td><td style="padding: 10px 0; font-weight: 700; color: ${item.status === 'success' ? '#059669' : '#dc2626'}; text-align: right;">${item.status.toUpperCase()}</td></tr>
          <tr style="border-bottom: 1px solid #f3f4f6;"><td style="padding: 10px 0; color: #6b7280;">Total Rows</td><td style="padding: 10px 0; font-weight: 600; color: #111827; text-align: right;">${total}</td></tr>
          <tr style="border-bottom: 1px solid #f3f4f6;"><td style="padding: 10px 0; color: #6b7280;">Valid Jobs</td><td style="padding: 10px 0; font-weight: 700; color: #059669; text-align: right;">${valid}</td></tr>
          <tr style="border-bottom: 1px solid #f3f4f6;"><td style="padding: 10px 0; color: #6b7280;">Failed Rows</td><td style="padding: 10px 0; font-weight: 600; color: ${failed > 0 ? '#dc2626' : '#6b7280'}; text-align: right;">${failed}</td></tr>
          <tr style="border-bottom: 1px solid #f3f4f6;"><td style="padding: 10px 0; color: #6b7280;">Duration</td><td style="padding: 10px 0; font-weight: 600; color: #111827; text-align: right;">${duration}ms</td></tr>
        </table>
        ${
          item.errors && item.errors.length > 0
            ? `<div style="background: #fef2f2; border: 1px solid #fee2e2; border-radius: 8px; padding: 12px; margin-bottom: 20px;">
                 <h4 style="color: #991b1b; margin: 0 0 6px 0; font-size: 13px;">Validation Errors:</h4>
                 <ul style="margin: 0; padding-left: 18px; font-size: 12px; color: #b91c1c;">
                   ${item.errors.map((e) => `<li>Line ${e.line}: ${e.message}</li>`).join('')}
                 </ul>
               </div>`
            : ''
        }
        <div style="text-align: center; margin-top: 24px;">
          <a href="${this.config.get<string>('FRONTEND_URL') || 'http://localhost:3000'}" style="background: #2563eb; color: #ffffff; padding: 10px 24px; border-radius: 8px; text-decoration: none; font-size: 14px; font-weight: 600; display: inline-block;">Open Job Monitor Dashboard</a>
        </div>
      </div>
    `;

    try {
      const from =
        this.config.get<string>('SMTP_FROM') ||
        `"Job Alert" <${this.defaultRecipient}>`;
      const info = await this.transporter.sendMail({
        from,
        to: recipient,
        subject,
        html,
        text: `File ${item.fileName} processed. Total: ${total}, Valid: ${valid}, Failed: ${failed}.`,
      });
      this.logger.log(`File processed summary email delivered to ${recipient}`);
      return { success: true, messageId: info.messageId, recipient };
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : String(err);
      this.logger.error(
        `Failed to dispatch file summary email to ${recipient}: ${msg}`,
      );
      return { success: false, recipient, error: msg };
    }
  }
}
